"""Новый контакт должен попадать в поле зрения оператора.

DevTools-обход 2026-08-01 (лид 244, «МЭЙДЖОР ЭКСПРЕСС»): кнопка «+ контакт»
висит в шапке панели, а форма добавляется в конец списка. Замер в браузере:
кнопка на y=-1019 (уже прокручена вверх), новая форма на y=828 при высоте
окна 666 — то есть на 1847 px ниже кнопки и за нижним краем экрана.

Оператор жал «+ контакт», ничего не видел, считал что кнопка не сработала,
и печатал в последнюю видимую форму — то есть правил предыдущий контакт.
Аудит лида это подтверждает: `арам3 → арам4 → арам5 → арам6`, второй контакт
переименовывался, третий не появлялся ни разу.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PANEL = ROOT / "frontend" / "src" / "components" / "LeadContactsPanel.svelte"


def _panel() -> str:
    return PANEL.read_text(encoding="utf-8")


def test_new_contact_row_is_addressable():
    """У строки контакта нужен якорь в DOM, иначе новую форму не найти."""
    assert "data-contact-row" in _panel(), (
        "нет якоря на строке контакта — некуда прокручивать и ставить фокус"
    )


def test_new_contact_scrolls_into_view():
    """После добавления форма прокручивается к оператору."""
    assert "scrollIntoView" in _panel(), (
        "новая форма остаётся за краем экрана — оператор её не видит и правит "
        "предыдущий контакт"
    )


def test_new_contact_gets_focus():
    """Курсор сразу в новой форме — печатать можно не целясь мышкой."""
    text = _panel()
    assert ".focus(" in text, "новая форма не получает фокус"
    assert "preventScroll" in text, (
        "focus() без preventScroll перебивает нашу прокрутку своей"
    )


def test_add_button_duplicated_at_list_end():
    """Вторая кнопка «+ контакт» — внизу, где список заканчивается."""
    text = _panel()
    assert text.count("+ контакт") >= 2, (
        "кнопка добавления только в шапке — на длинном списке до неё "
        "нужно листать вверх"
    )
